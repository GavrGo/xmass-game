// Логика Jira Fight (как Water Sort): доски, переливание, проверка решаемости, генерация уровней.
// Все числа берутся из config.ts (раздел ДЖИРА_ФАЙТ).
import { ДЖИРА_ФАЙТ as К } from "../config";
import { бонусЗарплатыПроц } from "./effects";

export type Режим = "zen" | "timed";
/** Доска = стопка задач (каждая задача — номер цвета/эпика). Элемент [0] лежит внизу, последний — сверху. */
export type Доски = number[][];

const ВМЕСТ = К.вместимостьДоски;

export const цветовНаУровне = (L: number) =>
  Math.min(К.цветов.максимум, К.цветов.старт + Math.floor((L - 1) / К.цветов.уровнейНаДобавлениеЦвета));
export const пустыхНаУровне = (L: number) => (L <= К.пустыхДосок.доУровня ? К.пустыхДосок.вНачале : К.пустыхДосок.потом);
export const доскНаУровне = (L: number) => цветовНаУровне(L) + пустыхНаУровне(L);

/** Доска собрана: заполнена целиком задачами одного цвета. Такая доска «закрыта» и больше не двигается. */
export const завершена = (д: number[]) => д.length === ВМЕСТ && д.every((x) => x === д[0]);

/** Сколько задач одного цвета лежит сверху доски подряд. */
export function верхняяПорция(д: number[]): number {
  if (!д.length) return 0;
  const цвет = д[д.length - 1];
  let n = 0;
  for (let i = д.length - 1; i >= 0 && д[i] === цвет; i--) n++;
  return n;
}

/**
 * Можно ли перелить с доски a на доску b.
 * Нельзя: из закрытой доски; на полную; на доску с другим верхним цветом;
 * и бессмысленно переносить доску одного цвета на пустую.
 */
export function можноПерелить(доски: Доски, a: number, b: number): boolean {
  if (a === b) return false;
  const A = доски[a], B = доски[b];
  if (!A.length || завершена(A)) return false;
  if (B.length >= ВМЕСТ) return false;
  const цвет = A[A.length - 1];
  if (B.length === 0) return !A.every((x) => x === цвет);
  return B[B.length - 1] === цвет;
}

/** Переливаем: сколько влезет задач верхнего цвета. */
export function перелить(доски: Доски, a: number, b: number): { доски: Доски; перелито: number } {
  const новые = доски.map((д) => [...д]);
  const A = новые[a], B = новые[b];
  const цвет = A[A.length - 1];
  let перелито = 0;
  while (A.length && A[A.length - 1] === цвет && B.length < ВМЕСТ) {
    B.push(A.pop()!);
    перелито++;
  }
  return { доски: новые, перелито };
}

/** Остался ли хоть один осмысленный ход. */
export function естьХод(доски: Доски): boolean {
  for (let a = 0; a < доски.length; a++)
    for (let b = 0; b < доски.length; b++) if (можноПерелить(доски, a, b)) return true;
  return false;
}

/** Уровень решён: каждая доска пуста или собрана. */
export const уровеньРешён = (доски: Доски) => доски.every((д) => д.length === 0 || завершена(д));

/** Проверка, что расклад вообще можно решить (поиск в глубину с ограничением). */
export function решаемо(начало: Доски): boolean {
  const ключ = (д: Доски) => д.map((x) => x.join("")).sort().join("|");
  const видели = new Set<string>([ключ(начало)]);
  const стек: Доски[] = [начало];
  let узлов = 0;
  while (стек.length) {
    const текущие = стек.pop()!;
    if (уровеньРешён(текущие)) return true;
    if (++узлов > К.лимитПоискаРешения) return false;
    for (let a = 0; a < текущие.length; a++) {
      for (let b = 0; b < текущие.length; b++) {
        if (!можноПерелить(текущие, a, b)) continue;
        const след = перелить(текущие, a, b).доски;
        const k = ключ(след);
        if (видели.has(k)) continue;
        видели.add(k);
        стек.push(след);
      }
    }
  }
  return false;
}

const перемешать = <T,>(список: T[]) => {
  const a = [...список];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

function случайныйРасклад(цветов: number, пустых: number): Доски {
  const задачи: number[] = [];
  for (let c = 0; c < цветов; c++) for (let k = 0; k < ВМЕСТ; k++) задачи.push(c);
  const м = перемешать(задачи);
  const доски: Доски = [];
  for (let i = 0; i < цветов; i++) доски.push(м.slice(i * ВМЕСТ, (i + 1) * ВМЕСТ));
  for (let i = 0; i < пустых; i++) доски.push([]);
  return доски;
}

/** Создаёт решаемый уровень без готовых досок. */
export function сгенерироватьУровень(L: number): Доски {
  const цветов = цветовНаУровне(L), пустых = пустыхНаУровне(L);
  for (let п = 0; п < К.попытокГенерации; п++) {
    const доски = случайныйРасклад(цветов, пустых);
    if (доски.some((д) => завершена(д))) continue;
    if (!естьХод(доски)) continue;
    if (решаемо(доски)) return доски;
  }
  // Запасной вариант (почти не бывает): добавляем ещё одну пустую доску
  return случайныйРасклад(цветов, пустых + 1);
}

/** Время на уровень в режиме «На время» (секунды). */
export const времяУровня = (L: number, бонусСек: number) =>
  Math.round(К.наВремя.базаСек + К.наВремя.наКаждуюДоскуСек * доскНаУровне(L) + бонусСек);

/** Награда: база × (0.5 в Дзене) × бонус «Повышение ЗП», округление вниз. */
export function наградаДжира(база: number, режим: Режим, уровеньЗП: number): number {
  const м = режим === "zen" ? К.дзенМножитель : 1;
  return Math.floor(база * м * (1 + бонусЗарплатыПроц({ salary_level: уровеньЗП }) / 100) + 1e-9);
}
