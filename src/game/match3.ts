// Логика «3 в ряд» без экрана: поле, совпадения, спецэффекты, падение, этапы.
// Все числа берутся из config.ts (раздел ТРИ_В_РЯД).
import { ТРИ_В_РЯД as К } from "../config";
import { бонусЗарплатыПроц } from "./effects";

export const N = К.размер;

export interface Клетка { id: number; тип: number }
export type Поле = (Клетка | null)[]; // N*N клеток по строкам, null = пусто

let счётчикId = 1;
const новыйId = () => счётчикId++;
const случайныйТип = () => Math.floor(Math.random() * К.символы.length);

export interface Серия { клетки: number[]; горизонталь: boolean; тип: number }
export type Эффект = "взрыв" | "линия" | "тип" | "ультра";
const ПРИОРИТЕТ: Эффект[] = ["взрыв", "линия", "тип", "ультра"];

/** Соседние ли клетки (по горизонтали или вертикали). */
export function соседи(a: number, b: number): boolean {
  const ar = Math.floor(a / N), ac = a % N, br = Math.floor(b / N), bc = b % N;
  return (ar === br && Math.abs(ac - bc) === 1) || (ac === bc && Math.abs(ar - br) === 1);
}

export function поменять(поле: Поле, a: number, b: number): Поле {
  const п = [...поле];
  [п[a], п[b]] = [п[b], п[a]];
  return п;
}

/** Все линии из 3 и более одинаковых символов. */
export function найтиСерии(поле: Поле): Серия[] {
  const серии: Серия[] = [];
  for (let r = 0; r < N; r++) {
    let c = 0;
    while (c < N) {
      const к = поле[r * N + c];
      if (!к) { c++; continue; }
      let e = c + 1;
      while (e < N && поле[r * N + e]?.тип === к.тип) e++;
      if (e - c >= 3) серии.push({ клетки: Array.from({ length: e - c }, (_, k) => r * N + c + k), горизонталь: true, тип: к.тип });
      c = e;
    }
  }
  for (let c = 0; c < N; c++) {
    let r = 0;
    while (r < N) {
      const к = поле[r * N + c];
      if (!к) { r++; continue; }
      let e = r + 1;
      while (e < N && поле[e * N + c]?.тип === к.тип) e++;
      if (e - r >= 3) серии.push({ клетки: Array.from({ length: e - r }, (_, k) => (r + k) * N + c), горизонталь: false, тип: к.тип });
      r = e;
    }
  }
  return серии;
}

/**
 * Что исчезнет. центры — клетки, которые игрок только что сдвинул (от них считается взрыв и линия).
 *  3 в ряд — только они; 4 — взрыв вокруг; 5 — вся линия; 6+ — все символы вида; ультиматумОтДлины+ — всё поле.
 */
export function разрушения(поле: Поле, серии: Серия[], центры: number[]) {
  const индексы = new Set<number>();
  let эффект: Эффект | null = null;
  const поднять = (э: Эффект) => {
    if (!эффект || ПРИОРИТЕТ.indexOf(э) > ПРИОРИТЕТ.indexOf(эффект)) эффект = э;
  };
  for (const с of серии) {
    с.клетки.forEach((i) => индексы.add(i));
    const дл = с.клетки.length;
    const центр = с.клетки.find((i) => центры.includes(i)) ?? с.клетки[Math.floor(дл / 2)];
    const r = Math.floor(центр / N), c = центр % N;
    if (дл >= К.ультиматумОтДлины) {
      поле.forEach((к, i) => { if (к) индексы.add(i); });
      поднять("ультра");
    } else if (дл >= 6) {
      поле.forEach((к, i) => { if (к && к.тип === с.тип) индексы.add(i); });
      поднять("тип");
    } else if (дл === 5) {
      for (let k = 0; k < N; k++) индексы.add(с.горизонталь ? r * N + k : k * N + c);
      поднять("линия");
    } else if (дл === 4) {
      for (let dr = -К.радиусВзрыва; dr <= К.радиусВзрыва; dr++) {
        for (let dc = -К.радиусВзрыва; dc <= К.радиусВзрыва; dc++) {
          const rr = r + dr, cc = c + dc;
          if (rr >= 0 && rr < N && cc >= 0 && cc < N) индексы.add(rr * N + cc);
        }
      }
      поднять("взрыв");
    }
  }
  return { индексы, эффект: эффект as Эффект | null };
}

/** Символы падают вниз, сверху появляются новые. */
export function упасть(поле: Поле): { поле: Поле; новые: Set<number> } {
  const новое: Поле = new Array(N * N).fill(null);
  const новые = new Set<number>();
  for (let c = 0; c < N; c++) {
    let запись = N - 1;
    for (let r = N - 1; r >= 0; r--) {
      const к = поле[r * N + c];
      if (к) { новое[запись * N + c] = к; запись--; }
    }
    for (let r = запись; r >= 0; r--) {
      const к = { id: новыйId(), тип: случайныйТип() };
      новое[r * N + c] = к;
      новые.add(к.id);
    }
  }
  return { поле: новое, новые };
}

/** Есть ли хоть один ход, который даёт совпадение. */
export function естьХод(поле: Поле): boolean {
  for (let i = 0; i < N * N; i++) {
    const r = Math.floor(i / N), c = i % N;
    if (c < N - 1 && найтиСерии(поменять(поле, i, i + 1)).length) return true;
    if (r < N - 1 && найтиСерии(поменять(поле, i, i + N)).length) return true;
  }
  return false;
}

/** Стартовое поле: без готовых совпадений, но с возможным ходом. */
export function начальноеПоле(): Поле {
  for (;;) {
    const п: Поле = new Array(N * N).fill(null);
    for (let i = 0; i < N * N; i++) {
      const r = Math.floor(i / N), c = i % N;
      let тип: number;
      do {
        тип = случайныйТип();
      } while (
        (c >= 2 && п[i - 1]?.тип === тип && п[i - 2]?.тип === тип) ||
        (r >= 2 && п[i - N]?.тип === тип && п[i - 2 * N]?.тип === тип)
      );
      п[i] = { id: новыйId(), тип };
    }
    if (естьХод(п)) return п;
  }
}

/** Когда ходов не осталось — перемешиваем символы на поле. */
export function перемешатьПоле(поле: Поле): Поле {
  const типы = поле.map((к) => к!.тип);
  for (let попытка = 0; попытка < 100; попытка++) {
    типы.sort(() => Math.random() - 0.5);
    const п: Поле = поле.map((к, i) => ({ id: к!.id, тип: типы[i] }));
    if (!найтиСерии(п).length && естьХод(п)) return п;
  }
  return начальноеПоле();
}

/** Очки за один шаг уборки. каскад: 1 — первое совпадение хода, 2 — цепная реакция, ... */
export function очкиЗаШаг(клеток: number, каскад: number): number {
  return Math.floor(клеток * К.очковЗаКлетку * (1 + К.бонусКаскада * (каскад - 1)));
}

// ---------- Этапы ----------
export const цельЭтапа = (этап: number) => К.цель.старт + К.цель.прирост * (этап - 1);
export const ходовЭтапа = (этап: number) => Math.max(К.ходов.минимум, Math.round(К.ходов.старт + К.ходов.изменение * (этап - 1)));

/** Награда за пройденный этап: база этапа + бонус за неиспользованные ходы, × «Повышение ЗП». */
export function наградаЭтапа(этап: number, осталосьХодов: number, уровеньЗП: number) {
  const база = К.награда.старт + К.награда.прирост * (этап - 1);
  const заХоды = осталосьХодов * К.наградаЗаОставшийсяХод;
  const бонусПроц = бонусЗарплатыПроц({ salary_level: уровеньЗП });
  return { база, заХоды, бонусПроц, итого: Math.floor((база + заХоды) * (1 + бонусПроц / 100) + 1e-9) };
}

