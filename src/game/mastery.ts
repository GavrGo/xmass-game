import { МАСТЕРСТВО, ИГРЫ_МАСТЕРСТВА } from "../config";

type Записи = Record<string, { xp: number } | undefined>;

export interface Требование { уровень: number; наУровне: number }

export function уровеньМастерства(xp: number) {
  const уровень = Math.min(МАСТЕРСТВО.максУровень, Math.floor(xp / МАСТЕРСТВО.очковНаУровень));
  const прогресс = уровень >= МАСТЕРСТВО.максУровень ? 1 : (xp % МАСТЕРСТВО.очковНаУровень) / МАСТЕРСТВО.очковНаУровень;
  return { уровень, прогресс, бонус: 1 + бонусНаУровне(уровень) };
}

export function бонусНаУровне(уровень: number) {
  return МАСТЕРСТВО.бонусНаМаксе * Math.pow(уровень / МАСТЕРСТВО.максУровень, МАСТЕРСТВО.степеньБонуса);
}

function потолок(игра: string, уровни: Record<string, number>) {
  const вторая = ИГРЫ_МАСТЕРСТВА.filter((id) => id !== игра).map((id) => уровни[id]).sort((a, b) => b - a)[1] ?? 0;
  return Math.min(МАСТЕРСТВО.максУровень, вторая + МАСТЕРСТВО.отрывУровней);
}

export function допустимыеУровни(записи: Записи | undefined): Record<string, number> {
  const уровни: Record<string, number> = {};
  for (const id of ИГРЫ_МАСТЕРСТВА) уровни[id] = уровеньМастерства(записи?.[id]?.xp ?? 0).уровень;
  let меняется = true;
  while (меняется) {
    меняется = false;
    for (const id of ИГРЫ_МАСТЕРСТВА) {
      const п = потолок(id, уровни);
      if (п < уровни[id]) { уровни[id] = п; меняется = true; }
    }
  }
  return уровни;
}

export function требование(уровень: number): Требование {
  return { уровень, наУровне: уровень - МАСТЕРСТВО.отрывУровней };
}

export function подсказкаТребования(т: Требование) {
  return `Чтобы прокачать ${т.уровень} уровень — достигните ${т.наУровне} уровня в двух любых других играх.`;
}

export function инфоМастерства(игра: string, записи: Записи | undefined) {
  const сырой = уровеньМастерства(записи?.[игра]?.xp ?? 0);
  const уровень = Math.min(сырой.уровень, допустимыеУровни(записи)[игра]);
  const заблокирован = уровень < сырой.уровень;
  return {
    уровень,
    прогресс: заблокирован ? 1 : сырой.прогресс,
    бонус: 1 + бонусНаУровне(уровень),
    заблокирован,
    следующее: требование(уровень + 1),
  };
}
