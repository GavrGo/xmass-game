import { МАСТЕРСТВО } from "../config";

export function уровеньМастерства(xp: number) {
  const уровень = Math.min(МАСТЕРСТВО.максУровень, Math.floor(xp / МАСТЕРСТВО.очковНаУровень));
  const прогресс = уровень >= МАСТЕРСТВО.максУровень ? 1 : (xp % МАСТЕРСТВО.очковНаУровень) / МАСТЕРСТВО.очковНаУровень;
  return { уровень, прогресс, бонус: 1 + уровень * МАСТЕРСТВО.бонусЗаУровень };
}

