// Логика слота: что выпало и сколько за это платить.
// Здесь НЕТ чисел и текстов — числа в config.ts, тексты в texts.ts.
import { СИМВОЛЫ_СЛОТА, СИМВОЛ_WILD, СЛОТ, СимволСлота, Награда } from "../config";
import { шансБесплатнойКрутки } from "./effects";
import { Т } from "../texts";

export interface ИтогСпина {
  символы: СимволСлота[];     // 3 выпавших символа
  награда: { chips: number; tickets: number; hearts: number }; // уже с учётом множителя ставки
  описание: string;           // текст для игрока
  бесплатнаяКрутка: boolean;  // выпал ли Free Spin
  тройка: boolean;
  символТройки?: СимволСлота; // какой символ собрал тройку (с учётом Wild); нужен для эффектов            // выпали ли 3 одинаковых символа (для эффектов)
}

/** Случайный символ с учётом весов (чем больше вес, тем чаще). */
export function случайныйСимвол(уровеньМусора = 0, сWild = false, уровеньОпыта = 1): СимволСлота {
  // Уровень мусора 0-4: каждый уровень убирает один мусорный символ
  const мусорные = СИМВОЛЫ_СЛОТА.filter(с => с.мусор);
  const убранные = new Set(мусорные.slice(0, уровеньМусора).map(с => с.id));
  // Wild (артефакт чёрного рынка) участвует в розыгрыше как обычный символ со своим весом
  const все = (сWild ? [...СИМВОЛЫ_СЛОТА, СИМВОЛ_WILD] : СИМВОЛЫ_СЛОТА).filter((с) => (с.открытьНаУровне ?? 1) <= уровеньОпыта);
  const доступные = все.filter(с => !убранные.has(с.id));
  const сумма = доступные.reduce((s, x) => s + x.вес, 0);
  let бросок = Math.random() * сумма;
  for (const с of доступные) {
    бросок -= с.вес;
    if (бросок < 0) return с;
  }
  return доступные[0];
}

/** Превращает награду в текст: «+100 🪙 +1 🎟️» */
export function текстНаграды(н: Награда): string {
  const части: string[] = [];
  if (н.фишки) части.push(Т.общее.плюсФишки(н.фишки));
  if (н.билеты) части.push(Т.общее.плюсБилеты(н.билеты));
  if (н.хэпэшки) части.push(Т.общее.плюсХэпэшки(н.хэпэшки));
  return части.join(" ");
}

/**
 * Одна крутка: бросаем 3 барабана, считаем награду и шанс Free Spin.
 * множитель — выбранный игроком (x1, x3, x5, x10): умножает награду, но НЕ блокировку после бомб.
 */
export function крутитьСлот(
  уровеньFreeSpin: number,
  бесплатнаяЭтаКрутка: boolean,
  множитель = 1,
  уровеньМусора = 0,
  сWild = false,
  уровеньОпыта = 1
): ИтогСпина {
  const символы = [случайныйСимвол(уровеньМусора, сWild, уровеньОпыта), случайныйСимвол(уровеньМусора, сWild, уровеньОпыта), случайныйСимвол(уровеньМусора, сWild, уровеньОпыта)];

  const умножить = (н: Награда): Награда => ({
    фишки: (н.фишки ?? 0) * множитель,
    билеты: (н.билеты ?? 0) * множитель,
    хэпэшки: (н.хэпэшки ?? 0) * множитель,
  });
  const приставка = Т.слот.приставка(множитель);

  // Считаем, сколько раз встретился каждый символ
  const счёт: Record<string, number> = {};
  символы.forEach((с) => (счёт[с.id] = (счёт[с.id] ?? 0) + 1));

  let награда: Награда = {};
  let описание: string = Т.слот.неПовезло;
  let тройка = false;
  let символТройки: СимволСлота | undefined;
  const wild = счёт["wild"] ?? 0; // Wild заменяет любую обычную картинку, но не бомбу и не мусор
  const естьWild = wild > 0;
  const ценность = (н: Награда) => (н.хэпэшки ?? 0) * 1e6 + (н.билеты ?? 0) * 1e3 + (н.фишки ?? 0);

  // Все подходящие комбинации; без Wild это ровно одна (или ни одной) — как раньше.
  const варианты: { с: СимволСлота; три: boolean; очки: number }[] = [];
  for (const с of СИМВОЛЫ_СЛОТА) {
    const всего = (счёт[с.id] ?? 0) + (с.бомба || с.мусор ? 0 : wild);
    if (всего === 3) варианты.push({ с, три: true, очки: 1e9 + ценность(с.за3) });
    else if (всего === 2 && текстНаграды(с.за2)) варианты.push({ с, три: false, очки: ценность(с.за2) });
  }
  const лучший = варианты.sort((x, y) => y.очки - x.очки)[0];
  if (лучший) {
    const { с } = лучший;
    const имя = Т.слот.родительный[с.id] ?? с.id;
    if (лучший.три) {
      награда = умножить(с.за3);
      тройка = true;
      символТройки = с;
      описание = с.бомба
        ? Т.слот.тройкаБомб(СЛОТ.блокировкаПослеБомбСекунд)
        : текстНаграды(награда) ? Т.слот.тройка(приставка, имя, текстНаграды(награда)) : Т.слот.тройкаПусто(имя);
    } else {
      награда = умножить(с.за2);
      описание = Т.слот.двойка(приставка, имя, текстНаграды(награда));
    }
  }

  // Wild собрал комбинацию — так и пишем игроку
  if (естьWild && тройка) описание += Т.слот.wildТройка;
  else if (естьWild && текстНаграды(награда)) описание += Т.слот.wildПомог;

  // Бросок на бесплатную крутку
  const можноБросать = !бесплатнаяЭтаКрутка || СЛОТ.бесплатнаяМожетВыпастьНаБесплатной;
  const бесплатнаяКрутка =
    можноБросать && Math.random() * 100 < шансБесплатнойКрутки({ free_spin_level: уровеньFreeSpin });

  return {
    символы,
    награда: { chips: награда.фишки ?? 0, tickets: награда.билеты ?? 0, hearts: награда.хэпэшки ?? 0 },
    описание,
    бесплатнаяКрутка,
    тройка,
    символТройки,
  };
}
