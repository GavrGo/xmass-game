// Логика слота: что выпало и сколько за это платить.
// Здесь НЕТ чисел — все они в config.ts.
import { СИМВОЛЫ_СЛОТА, СЛОТ, СимволСлота, Награда } from "../config";
import { шансБесплатнойКрутки } from "./effects";

export interface ИтогСпина {
  символы: СимволСлота[];     // 3 выпавших символа
  награда: { chips: number; tickets: number; hearts: number };
  описание: string;           // текст для игрока
  бесплатнаяКрутка: boolean;  // выпал ли Free Spin
  тройка: boolean;            // выпали ли 3 одинаковых символа (для эффектов)
}

/** Случайный символ с учётом весов (чем больше вес, тем чаще). */
export function случайныйСимвол(): СимволСлота {
  const сумма = СИМВОЛЫ_СЛОТА.reduce((s, x) => s + x.вес, 0);
  let бросок = Math.random() * сумма;
  for (const с of СИМВОЛЫ_СЛОТА) {
    бросок -= с.вес;
    if (бросок < 0) return с;
  }
  return СИМВОЛЫ_СЛОТА[0];
}

/** Превращает награду в текст: «+100 🪙 +1 🎟️» */
export function текстНаграды(н: Награда): string {
  const части: string[] = [];
  if (н.фишки) части.push(`+${н.фишки} 🪙`);
  if (н.билеты) части.push(`+${н.билеты} 🎟️`);
  if (н.хэпэшки) части.push(`+${н.хэпэшки} ❤️`);
  return части.join(" ");
}

/** Одна крутка: бросаем 3 барабана, считаем награду и шанс Free Spin. */
export function крутитьСлот(
  уровеньFreeSpin: number,
  бесплатнаяЭтаКрутка: boolean
): ИтогСпина {
  const символы = [случайныйСимвол(), случайныйСимвол(), случайныйСимвол()];

  // Считаем, сколько раз встретился каждый символ
  const счёт: Record<string, number> = {};
  символы.forEach((с) => (счёт[с.id] = (счёт[с.id] ?? 0) + 1));

  let награда: Награда = {};
  let описание = "Не повезло, пробуйте ещё";
  let тройка = false;
  for (const с of СИМВОЛЫ_СЛОТА) {
    if (счёт[с.id] === 3) {
      награда = с.за3;
      тройка = true;
      описание = с.бомба
        ? `Три бомбы! 💥 Слот заблокирован на ${СЛОТ.блокировкаПослеБомбСекунд} сек`
        : текстНаграды(с.за3) ? `Три ${с.название}! ${текстНаграды(с.за3)}` : `Три ${с.название}… и ничего`;
    } else if (счёт[с.id] === 2 && текстНаграды(с.за2)) {
      награда = с.за2;
      описание = `Два ${с.название}: ${текстНаграды(с.за2)}`;
    }
  }

  // Бросок на бесплатную крутку
  const можноБросать = !бесплатнаяЭтаКрутка || СЛОТ.бесплатнаяМожетВыпастьНаБесплатной;
  const бесплатнаяКрутка =
    можноБросать && Math.random() * 100 < шансБесплатнойКрутки({ free_spin_level: уровеньFreeSpin });

  return {
    символы,
    награда: { chips: награда.фишки ?? 0, tickets: награда.билеты ?? 0, hearts: награда.хэпэшки ?? 0 },
    описание,
    бесплатнаяКрутка,
    тройка,
  };
}
