// Расчёт обмена с комиссией.
import { ОБМЕН } from "../config";

export type Направление = "chipsToTickets" | "ticketsToChips";

/**
 * количество — сколько игрок ввёл (фишек или билетов, зависит от направления).
 * Возвращает: получите — сколько придёт, спишется — сколько реально уйдёт.
 * (Если введено больше, чем нужно на целое число билетов, лишние фишки не сгорают.)
 */
export function посчитатьОбмен(напр: Направление, количество: number, комиссияПроц: number) {
  const доля = (100 - комиссияПроц) / 100; // какая часть остаётся после комиссии
  if (доля <= 0 || количество <= 0) return { получите: 0, спишется: 0 };

  if (напр === "chipsToTickets") {
    const получите = Math.floor((количество * доля) / ОБМЕН.фишекЗаБилет + 1e-9);
    const спишется = получите > 0 ? Math.ceil((получите * ОБМЕН.фишекЗаБилет) / доля - 1e-9) : 0;
    return { получите, спишется };
  }
  const получите = Math.floor(количество * ОБМЕН.фишекЗаБилет * доля + 1e-9);
  return { получите, спишется: количество };
}
