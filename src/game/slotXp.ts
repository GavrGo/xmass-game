import { ОПЫТ_СЛОТА } from "../config";

export function уровеньОпытаСлота(спинов: number) {
  const { спинов: пороги, множители } = ОПЫТ_СЛОТА;
  let индекс = 0;
  while (индекс + 1 < пороги.length && спинов >= пороги[индекс + 1]) индекс++;
  const следующийПорог = индекс + 1 < пороги.length ? пороги[индекс + 1] : null;
  const прогресс = следующийПорог === null ? 1 : (спинов - пороги[индекс]) / (следующийПорог - пороги[индекс]);
  return { уровень: индекс + 1, множитель: множители[индекс], прогресс, следующийПорог };
}
