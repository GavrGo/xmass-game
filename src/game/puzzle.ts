// Логика Пятнашек: перемешивание, ходы, награда. Числа берутся из config.ts (ПЯТНАШКИ).
import { ПЯТНАШКИ } from "../config";
import { бонусЗарплатыПроц } from "./effects";

const N = ПЯТНАШКИ.размер;
export const ПУСТАЯ = N * N - 1; // номер «пустой» плитки (последняя)

export type Режим = "zen" | "timed";

/** Доска = список из N*N чисел: на каждой позиции лежит номер плитки. Решённая: 0,1,2,...,15. */
export const решённая = (): number[] => Array.from({ length: N * N }, (_, i) => i);
export const собрана = (д: number[]) => д.every((v, i) => v === i);

/**
 * Нажали на клетку с индексом i. Если она в одном ряду/столбце с пустой клеткой —
 * сдвигаем всю линию к пустой клетке. Иначе возвращаем null (ход невозможен).
 */
export function сдвинуть(д: number[], i: number): number[] | null {
  const e = д.indexOf(ПУСТАЯ);
  if (i === e) return null;
  const er = Math.floor(e / N), ec = e % N, r = Math.floor(i / N), c = i % N;
  if (er !== r && ec !== c) return null;
  const шаг = er === r ? (c > ec ? 1 : -1) : r > er ? N : -N;
  const новая = [...д];
  let k = e;
  while (k !== i) { новая[k] = новая[k + шаг]; k += шаг; }
  новая[i] = ПУСТАЯ;
  return новая;
}

/** Перемешивание случайными ходами из решённого состояния — так пазл ВСЕГДА решаем. */
export function перемешать(): number[] {
  let д = решённая();
  let e = ПУСТАЯ, предыдущая = -1;
  for (let k = 0; k < ПЯТНАШКИ.перемешиваний; k++) {
    const r = Math.floor(e / N), c = e % N;
    const соседи: number[] = [];
    if (r > 0) соседи.push(e - N);
    if (r < N - 1) соседи.push(e + N);
    if (c > 0) соседи.push(e - 1);
    if (c < N - 1) соседи.push(e + 1);
    const варианты = соседи.filter((s) => s !== предыдущая);
    const j = варианты[Math.floor(Math.random() * варианты.length)];
    [д[e], д[j]] = [д[j], д[e]];
    предыдущая = e;
    e = j;
  }
  return собрана(д) ? перемешать() : д;
}

/** Награда: база зависит от режима и результата, потом × бонус «Повышение ЗП». */
export function наградаЗаПазл(режим: Режим, победа: boolean, уровеньЗП: number) {
  const база =
    режим === "zen"
      ? (победа ? ПЯТНАШКИ.дзен.награда : 0)
      : (победа ? ПЯТНАШКИ.наВремя.наградаЗаСборку : ПЯТНАШКИ.наВремя.утешительнаяНаграда);
  const бонусПроц = бонусЗарплатыПроц({ salary_level: уровеньЗП });
  return { база, бонусПроц, итого: Math.floor(база * (1 + бонусПроц / 100) + 1e-9) };
}

/** «1 пазл», «2 пазла», «5 пазлов» */
export function пазлов(n: number): string {
  const a = n % 100, b = n % 10;
  const слово = a >= 11 && a <= 14 ? "пазлов" : b === 1 ? "пазл" : b >= 2 && b <= 4 ? "пазла" : "пазлов";
  return `${n} ${слово}`;
}
