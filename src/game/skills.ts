export function навыкиИгры(игра: ИграСНавыками): Навык[] {
  return НАВЫКИ.filter((н) => н.игра === игра);
}

export function открытыеНавыки(игра: ИграСНавыками, уровеньМастерства: number): Навык[] {
  return навыкиИгры(игра).filter((н) => уровеньМастерства >= н.уровень);
}

export function навыкОткрыт(id: ИдНавыка, уровеньМастерства: number): boolean {
  return НАВЫКИ.some((н) => н.id === id && уровеньМастерства >= н.уровень);
}
