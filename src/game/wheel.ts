// Логика колеса фортуны: секторы, выбор результата, расчёт угла поворота. Числа — в config.ts (КОЛЕСО).
import { КОЛЕСО, ВалютаКолеса } from "../config";

export interface Сектор {
  множитель: number; // 0 = череп
  от: number;        // начало сектора, градусы по часовой стрелке от верхней точки
  до: number;        // конец сектора
  вес: number;
}

/** Секторы колеса для выбранной валюты: ширина сектора пропорциональна его весу (= шансу). */
export function собратьСектора(валюта: ВалютаКолеса): Сектор[] {
  const w = КОЛЕСО.веса[валюта];
  const веса = КОЛЕСО.сектора.map((м) => (м === 0 ? w.череп : w.множитель));
  const сумма = веса.reduce((a, b) => a + b, 0);
  let угол = 0;
  return КОЛЕСО.сектора.map((м, i) => {
    const ширина = (веса[i] / сумма) * 360;
    const с = { множитель: м, от: угол, до: угол + ширина, вес: веса[i] };
    угол += ширина;
    return с;
  });
}

/** Случайный сектор с учётом весов. */
export function выбратьСектор(секторы: Сектор[]): number {
  const сумма = секторы.reduce((a, с) => a + с.вес, 0);
  let бросок = Math.random() * сумма;
  for (let i = 0; i < секторы.length; i++) {
    бросок -= секторы[i].вес;
    if (бросок < 0) return i;
  }
  return секторы.length - 1;
}

/** Новый общий угол поворота колеса так, чтобы указатель (сверху) остановился внутри нужного сектора. */
export function новыйПоворот(текущий: number, сектор: Сектор): number {
  const середина = (сектор.от + сектор.до) / 2;
  const разброс = (сектор.до - сектор.от) * 0.35 * (Math.random() * 2 - 1); // не ровно по центру, а чуть случайно
  const цель = середина + разброс;
  const доцели = (((-цель - текущий) % 360) + 360) % 360;
  return текущий + 360 * КОЛЕСО.вращение.оборотов + доцели;
}

/** Какой сектор сейчас под указателем при общем повороте колеса. */
export function секторПодУказателем(секторы: Сектор[], поворот: number): number {
  const угол = (((-поворот) % 360) + 360) % 360;
  const i = секторы.findIndex((с) => угол >= с.от && угол < с.до);
  return i < 0 ? секторы.length - 1 : i;
}

/** Выплата за ставку: целое число (дробная часть отбрасывается). */
export function выплата(ставка: number, множитель: number): number {
  return множитель === 0 ? 0 : Math.floor(ставка * множитель);
}

/** Ожидаемый возврат ставки (1 = 100%) — для справки. */
export function ожидаемыйВозврат(валюта: ВалютаКолеса): number {
  const с = собратьСектора(валюта);
  const сумма = с.reduce((a, x) => a + x.вес, 0);
  return с.reduce((a, x) => a + x.вес * x.множитель, 0) / сумма;
}
