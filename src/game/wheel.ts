// Логика колеса фортуны: секторы, выбор результата, расчёт угла поворота. Числа — в config.ts (КОЛЕСО).
import { КОЛЕСО, ВалютаКолеса, ЧЁРНЫЙ_РЫНОК } from "../config";

export interface Сектор {
  множитель: number; // 0 = череп
  от: number;        // начало сектора, градусы по часовой стрелке от верхней точки
  до: number;        // конец сектора
  вес: number;
  золотой?: boolean; // артефакт x100
}

/** Секторы колеса для выбранной валюты: ширина сектора пропорциональна его весу (= шансу). Золотой x100 — только у купивших артефакт. */
export function собратьСектора(валюта: ВалютаКолеса, сX100 = false): Сектор[] {
  const w = КОЛЕСО.веса[валюта];
  const строки: { множитель: number; вес: number; золотой?: boolean }[] = КОЛЕСО.сектора.map((м) => ({
    множитель: м,
    вес: м === 0 ? w.череп : w.множитель,
  }));
  if (сX100) {
    const д = ЧЁРНЫЙ_РЫНОК.колесоX100.долляКруга;
    const остальные = строки.reduce((a, x) => a + x.вес, 0);
    const позиция = Math.min(строки.length, Math.max(0, ЧЁРНЫЙ_РЫНОК.колесоX100.позиция));
    строки.splice(позиция, 0, { множитель: ЧЁРНЫЙ_РЫНОК.колесоX100.множитель, вес: (остальные * д) / (1 - д), золотой: true });
  }
  const сумма = строки.reduce((a, x) => a + x.вес, 0);
  let угол = 0;
  return строки.map((x) => {
    const ширина = (x.вес / сумма) * 360;
    const с: Сектор = { множитель: x.множитель, от: угол, до: угол + ширина, вес: x.вес, золотой: x.золотой };
    угол += ширина;
    return с;
  });
}

/** Случайный сектор с учётом весов. */
export function выбратьСектор(секторы: Сектор[]): number {
  const сумма = секторы.reduce((a, с) => a + с.вес, 0);
  let бросок = Math.random() * сумма;
  for (let i = 0; i < секторы.length; i++) {
    бросок -= секторы[i].вес;
    if (бросок < 0) return i;
  }
  return секторы.length - 1;
}

/** Новый общий угол поворота колеса так, чтобы указатель (сверху) остановился внутри нужного сектора. */
export function новыйПоворот(текущий: number, сектор: Сектор): number {
  const середина = (сектор.от + сектор.до) / 2;
  const разброс = (сектор.до - сектор.от) * 0.35 * (Math.random() * 2 - 1); // не ровно по центру, а чуть случайно
  const цель = середина + разброс;
  const доцели = (((-цель - текущий) % 360) + 360) % 360;
  return текущий + 360 * КОЛЕСО.вращение.оборотов + доцели;
}

/** Какой сектор сейчас под указателем при общем повороте колеса. */
export function секторПодУказателем(секторы: Сектор[], поворот: number): number {
  const угол = (((-поворот) % 360) + 360) % 360;
  const i = секторы.findIndex((с) => угол >= с.от && угол < с.до);
  return i < 0 ? секторы.length - 1 : i;
}

/** Выплата за ставку: целое число (дробная часть отбрасывается). */
export function выплата(ставка: number, множитель: number): number {
  return множитель === 0 ? 0 : Math.floor(ставка * множитель);
}

/** Ожидаемый возврат ставки (1 = 100%) — для справки. */
export function ожидаемыйВозврат(валюта: ВалютаКолеса, сX100 = false): number {
  const с = собратьСектора(валюта, сX100);
  const сумма = с.reduce((a, x) => a + x.вес, 0);
  return с.reduce((a, x) => a + x.вес * x.множитель, 0) / сумма;
}

/** Текущий угол диска (0..360) из CSS-матрицы; null, если трансформации нет. */
export function уголДиска(элемент: Element): number | null {
  const m = getComputedStyle(элемент).transform;
  const v = m && m !== "none" ? m.match(/matrix\(([^)]+)\)/)?.[1].split(",").map(Number) : null;
  if (!v) return null;
  return (((Math.atan2(v[1], v[0]) * 180) / Math.PI) % 360 + 360) % 360;
}

/**
 * Сколько границ секторов прошло под указателем между двумя кадрами.
 * Колесо крутится по часовой, граница на угле β оказывается под указателем при полном повороте A ≡ −β (mod 360).
 */
export function границПройдено(секторы: Сектор[], A0: number, A1: number): number {
  let n = 0;
  for (const с of секторы) n += Math.floor((A1 + с.от) / 360) - Math.floor((A0 + с.от) / 360);
  return n;
}
