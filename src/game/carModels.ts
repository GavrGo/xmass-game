// Цвета граней по нормали: верх — краска, борта — затемнённые, торцы — тёмные.
function autoBody(prof: number[][], pal: Palette): string[] {
  const n = prof.length;
  const ca = prof.reduce((t, p) => t + p[0], 0) / n;
  const cz = prof.reduce((t, p) => t + p[1], 0) / n;
  const out: string[] = [];
  for (let i = 0; i < n; i++) {
    const [pa, pz] = prof[i];
    const [qa, qz] = prof[(i + 1) % n];
    let na = qz - pz;
    let nz = pa - qa;
    if (na * ((pa + qa) / 2 - ca) + nz * ((pz + qz) / 2 - cz) < 0) {
      na = -na;
      nz = -nz;
    }
    const len = Math.hypot(na, nz) || 1;
    na /= len;
    nz /= len;
    if (nz > 0.55) out.push(pal.top);
    else if (nz < -0.55) out.push("#0a0a0c");
    else if (Math.abs(na) > 0.55) out.push(pal.end);
    else out.push(pal.side);
  }
  return out;
}

// Кабина: крыша — цвет кузова, наклонные грани — стекло.
function autoCabin(prof: number[][], pal: Palette): string[] {
  const n = prof.length;
  const ca = prof.reduce((t, p) => t + p[0], 0) / n;
  const cz = prof.reduce((t, p) => t + p[1], 0) / n;
  const out: string[] = [];
  for (let i = 0; i < n; i++) {
    const [pa, pz] = prof[i];
    const [qa, qz] = prof[(i + 1) % n];
    let na = qz - pz;
    let nz = pa - qa;
    if (na * ((pa + qa) / 2 - ca) + nz * ((pz + qz) / 2 - cz) < 0) {
      na = -na;
      nz = -nz;
    }
    const len = Math.hypot(na, nz) || 1;
    const u = nz / len;
    out.push(u > 0.93 || u < -0.8 ? pal.cabin : pal.glass);
  }
  return out;
}

export function buildCar(model: number, pal: Palette, api: ModelApi) {
  const m = CAR_MODELS[((model % CAR_MODELS.length) + CAR_MODELS.length) % CAR_MODELS.length];
  api.pal = pal;
  m.build(api);
}

