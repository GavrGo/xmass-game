export type КлючПрокачки = keyof typeof ПРОКАЧКИ;

/** Цена покупки СЛЕДУЮЩЕГО уровня, если сейчас у игрока уровень `текущий`. */
export function ценаСледующегоУровня(ключ: КлючПрокачки, текущий: number): number {
  const п = ПРОКАЧКИ[ключ];
  return Math.ceil(п.базоваяЦена * Math.pow(п.множительЦены, текущий));
}

