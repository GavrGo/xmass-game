// =====================================================================
//  ПРОКАЧКИ (покупаются за фишки)
// =====================================================================
// Цена следующего уровня = базоваяЦена * (множительЦены ^ текущийУровень), округляется вверх.
// Эффект = эффектЗаУровень * текущийУровень.
export interface ПрокачкаКонфиг {
  название: string;        // что видит игрок
  описание: string;        // пояснение для игрока
  максУровень: number;     // потолок уровня
  базоваяЦена: number;     // цена 1-го уровня (в фишках)
  множительЦены: number;   // во сколько раз растёт цена с каждым уровнем
  эффектЗаУровень: number; // сколько даёт каждый уровень
  единица: string;         // "%" или "сек" — для отображения
  знак: "+" | "−";         // для отображения: прибавляет или уменьшает
}

