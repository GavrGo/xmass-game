// Цена следующего уровня = базоваяЦена * (множительЦены ^ текущийУровень), округляется вверх.
// Эффект = эффектЗаУровень * текущийУровень.
export interface ПрокачкаКонфиг {
  максУровень: number;
  базоваяЦена: number;
  множительЦены: number;
  эффектЗаУровень: number;
  фиксированныеЦены?: number[]; // если задано — цены берутся отсюда по индексу уровня
}
