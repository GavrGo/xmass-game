function тень(х: Состояние, режим: "normal" | "pressed" | "disabled"): string {
  if (!х.кант) return "";
  const к = х.кант;
  if (режим === "normal")
    return `box-shadow:0 6px 0 ${к},0 0 0 7px ${П.серебро},0 13px 0 7px ${П.сереброТёмное},0 22px 26px rgba(0,0,0,.55);`;
  if (режим === "pressed")
    return `transform:translateY(4px);box-shadow:0 2px 0 ${к},0 0 0 7px ${П.серебро},0 9px 0 7px ${П.сереброТёмное},0 14px 18px rgba(0,0,0,.55);`;
  return `box-shadow:0 4px 0 ${к},0 0 0 7px #3b3c42,0 11px 0 7px #2c2d32,0 18px 22px rgba(0,0,0,.5);`;
}

function блок(селектор: string, х: Состояние, дополнение: string): string {
  const рамка = х.рамка ? `border:2px solid ${х.рамка};` : "";
  return `${селектор}{background:${х.фон};color:${х.текст};${рамка}${дополнение}}`;
}

const КОД_СТИЛЕЙ = [
  `:root{--overlay-menu:${ОВЕРЛЕИ.меню};}`,
  ...(Object.values(РОЛИ_КНОПОК) as unknown as Роль[]).flatMap((р) => [
    блок(`.${р.класс}`, р.обычная, тень(р.обычная, "normal")),
    блок(`.${р.класс}:active:not(:disabled)`, р.нажата, тень(р.нажата, "pressed")),
    блок(`.${р.класс}:disabled`, р.отключена, тень(р.отключена, "disabled")),
  ]),
].join("\n");

export function применитьТему(): void {
  const стиль = document.createElement("style");
  стиль.textContent = КОД_СТИЛЕЙ;
  document.head.appendChild(стиль);
}
