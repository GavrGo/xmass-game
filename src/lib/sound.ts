// Звуковой менеджер: фоновая музыка и короткие звуки по событиям.
// Файлы кладите в public/sounds/music/ и public/sounds/sfx/ (имена — в src/config.ts, раздел ЗВУКИ).
// Нет файла — звук просто не играет, ничего не ломается.
//
// Как подключить звук в коде:   звук.sfx("победа");
// Как сменить музыку:            звук.музыка("игра");
import { ЗВУКИ, ЭффектЗвука, ТрекМузыки } from "../config";
import { естьФайл } from "./assets";

const КЛЮЧ_МУЗЫКА = "100hp_music_on";
const КЛЮЧ_ЭФФЕКТЫ = "100hp_sfx_on";

function прочитать(ключ: string, поУмолчанию: boolean): boolean {
  try {
    const v = localStorage.getItem(ключ);
    return v === null ? поУмолчанию : v === "1";
  } catch { return поУмолчанию; }
}
function записать(ключ: string, значение: boolean) {
  try { localStorage.setItem(ключ, значение ? "1" : "0"); } catch {}
}

class ЗвуковойМенеджер {
  музыкаВкл = прочитать(КЛЮЧ_МУЗЫКА, ЗВУКИ.музыкаПоУмолчанию);
  эффектыВкл = прочитать(КЛЮЧ_ЭФФЕКТЫ, ЗВУКИ.эффектыПоУмолчанию);

  private запрошенныйТрек: ТрекМузыки | null = "главная";
  private играющийТрек: ТрекМузыки | null = null;
  private аудио: HTMLAudioElement | null = null;
  private разрешено = false; // браузеры разрешают звук только после касания экрана
  private слушатели = new Set<() => void>();

  /** Подписка на изменения (для кнопки «звук вкл/выкл»). Возвращает функцию отписки. */
  подписаться(f: () => void): () => void {
    this.слушатели.add(f);
    return () => { this.слушатели.delete(f); };
  }
  private сообщить() { this.слушатели.forEach((f) => f()); }

  /** Вызвать один раз при старте приложения: ждём первое касание, чтобы можно было включить музыку. */
  инициализировать() {
    const разблокировать = () => {
      this.разрешено = true;
      this.применить();
      window.removeEventListener("pointerdown", разблокировать);
      window.removeEventListener("keydown", разблокировать);
    };
    window.addEventListener("pointerdown", разблокировать);
    window.addEventListener("keydown", разблокировать);
  }

  /** Короткий звук по событию. */
  sfx(имя: ЭффектЗвука) {
    if (!this.эффектыВкл) return;
    const путь = ЗВУКИ.папкаЭффектов + ЗВУКИ.эффекты[имя];
    if (естьФайл(путь) === false) return;
    try {
      const a = new Audio("/" + путь);
      a.volume = ЗВУКИ.громкостьЭффектов;
      void a.play().catch(() => {});
    } catch {}
  }

  /** Включить фоновый трек (null — тишина). */
  музыка(трек: ТрекМузыки | null) {
    this.запрошенныйТрек = трек;
    this.применить();
  }

  private применить() {
    const хотим = this.музыкаВкл && this.разрешено ? this.запрошенныйТрек : null;
    if (хотим === this.играющийТрек) return;
    if (this.аудио) { this.аудио.pause(); this.аудио = null; }
    this.играющийТрек = null;
    if (!хотим) return;
    const путь = ЗВУКИ.папкаМузыки + ЗВУКИ.музыка[хотим];
    if (естьФайл(путь) === false) return;
    try {
      const a = new Audio("/" + путь);
      a.loop = true;
      a.volume = ЗВУКИ.громкостьМузыки;
      void a.play().catch(() => {});
      this.аудио = a;
      this.играющийТрек = хотим;
    } catch {}
  }

  переключитьМузыку() {
    this.музыкаВкл = !this.музыкаВкл;
    записать(КЛЮЧ_МУЗЫКА, this.музыкаВкл);
    this.применить();
    this.сообщить();
  }

  переключитьЭффекты() {
    this.эффектыВкл = !this.эффектыВкл;
    записать(КЛЮЧ_ЭФФЕКТЫ, this.эффектыВкл);
    this.сообщить();
  }
}

export const звук = new ЗвуковойМенеджер();
